/** translate 服务实现：先做占位符替换，再查中文映射（精确匹配→大小写不敏感兜底），未命中返回原文 */
const ZH_LOWER = Object.fromEntries(Object.entries(ZH).map(([k, v]) => [k.toLowerCase(), v]))

export function translateZh(template, replacements) {
  replacements = replacements || {}
  let out = template
  try {
    out = String(template).replace(/\{([^}]+)\}/g, (m, k) => (replacements[k] !== undefined && replacements[k] !== null ? replacements[k] : m))
  } catch (e) { /* ignore */ }
  if (ZH[out]) return ZH[out]
  const hit = ZH_LOWER[String(out).toLowerCase()]
  if (hit) return hit
  return out
}

